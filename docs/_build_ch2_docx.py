h3("2.3.5. Пример эндпоинта")

p("Ниже приведён характерный пример эндпоинта получения "
  "ближайших аптек по геолокации с использованием формулы "
  "Haversine для расчёта расстояний:")

code_block(
    "@router.get('/nearby', response_model=list[BranchOut])\n"
    "async def nearby_branches(\n"
    "    lat: float,\n"
    "    lon: float,\n"
    "    radius_km: float = 5.0,\n"
    "    db: AsyncSession = Depends(get_db),\n"
    "):\n"
    "    haversine = (\n"
    "        6371 * func.acos(\n"
    "            func.cos(func.radians(lat))\n"
    "            * func.cos(func.radians(PharmacyBranch.latitude))\n"
    "            * func.cos(func.radians(PharmacyBranch.longitude) - func.radians(lon))\n"
    "            + func.sin(func.radians(lat))\n"
    "            * func.sin(func.radians(PharmacyBranch.latitude))\n"
    "        )\n"
    "    ).label('distance_km')\n"
    "    stmt = (\n"
    "        select(PharmacyBranch, haversine)\n"
    "        .where(PharmacyBranch.is_active.is_(True))\n"
    "        .having(haversine < radius_km)\n"
    "        .order_by(haversine)\n"
    "        .options(selectinload(PharmacyBranch.photos))\n"
    "    )\n"
    "    result = await db.execute(stmt)\n"
    "    return [BranchOut.model_validate(b, context={'distance_km': d})\n"
    "            for b, d in result.all()]"
)

p("Формула Haversine рассчитывает расстояние между двумя "
  "точками на поверхности Земли по их географическим "
  "координатам с учётом сферической формы планеты. Радиус "
  "Земли в формуле принят равным 6 371 км. Все тригонометрические "
  "операции выполняются на стороне базы данных средствами "
  "PostgreSQL, что обеспечивает высокую производительность "
  "запроса даже при большом числе филиалов в каталоге.")

